CREATE TABLE scanner_devices (
  id uuid PRIMARY KEY,
  owner_id text NOT NULL REFERENCES users(id),
  event_id integer NOT NULL REFERENCES events(id),
  gate_id integer NOT NULL REFERENCES gates(id),
  name text NOT NULL,
  registered_at timestamptz NOT NULL DEFAULT now(),
  bootstrap_at timestamptz,
  last_sync_at timestamptz,
  revocation_cursor bigint NOT NULL DEFAULT 0 CHECK(revocation_cursor>=0),
  revoked_at timestamptz
);
CREATE INDEX scanner_devices_event ON scanner_devices(event_id,last_sync_at);

CREATE TABLE scanner_shifts (
  id uuid PRIMARY KEY,
  device_id uuid NOT NULL REFERENCES scanner_devices(id),
  staff_id text NOT NULL REFERENCES users(id),
  event_id integer NOT NULL REFERENCES events(id),
  gate_id integer NOT NULL REFERENCES gates(id),
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz
);
CREATE INDEX scanner_shifts_device ON scanner_shifts(device_id,started_at DESC);

-- ticket_id deliberately has no foreign key: malformed and unknown tickets
-- remain evidence rather than disappearing when rejected at synchronization.
CREATE TABLE scanner_attempts (
  client_scan_id uuid PRIMARY KEY,
  device_id uuid NOT NULL REFERENCES scanner_devices(id),
  shift_id uuid NOT NULL REFERENCES scanner_shifts(id),
  staff_id text NOT NULL REFERENCES users(id),
  ticket_id text,
  event_id integer NOT NULL REFERENCES events(id),
  gate_id integer NOT NULL REFERENCES gates(id),
  credential_version integer,
  scanned_at timestamptz NOT NULL,
  synced_at timestamptz NOT NULL DEFAULT now(),
  local_result text NOT NULL,
  server_result text NOT NULL,
  payload_hash text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '{}'
);
CREATE INDEX scanner_attempts_event_cursor ON scanner_attempts(event_id,synced_at DESC,client_scan_id);
CREATE INDEX scanner_attempts_ticket ON scanner_attempts(ticket_id,event_id);
CREATE INDEX scanner_attempts_gate_hour ON scanner_attempts(event_id,gate_id,scanned_at);

CREATE TABLE scanner_admissions (
  event_id integer NOT NULL REFERENCES events(id),
  ticket_id text NOT NULL REFERENCES tickets(id),
  client_scan_id uuid NOT NULL UNIQUE REFERENCES scanner_attempts(client_scan_id),
  gate_id integer NOT NULL REFERENCES gates(id),
  admitted_at timestamptz NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(event_id,ticket_id)
);
CREATE INDEX scanner_admissions_gate ON scanner_admissions(event_id,gate_id,admitted_at);

CREATE TABLE scanner_incidents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES events(id),
  device_id uuid REFERENCES scanner_devices(id),
  client_scan_id uuid REFERENCES scanner_attempts(client_scan_id),
  type text NOT NULL,
  severity text NOT NULL DEFAULT 'warning' CHECK(severity IN ('info','warning','critical')),
  details jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX scanner_incidents_event_cursor ON scanner_incidents(event_id,id DESC);

-- Runtime and even accidental code changes cannot rewrite scanner evidence.
CREATE FUNCTION immutable_scanner_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'scanner evidence is append-only'; END $$;
CREATE TRIGGER scanner_attempts_no_change BEFORE UPDATE OR DELETE ON scanner_attempts
  FOR EACH ROW EXECUTE FUNCTION immutable_scanner_history();
CREATE TRIGGER scanner_admissions_no_change BEFORE UPDATE OR DELETE ON scanner_admissions
  FOR EACH ROW EXECUTE FUNCTION immutable_scanner_history();
CREATE TRIGGER scanner_incidents_no_change BEFORE UPDATE OR DELETE ON scanner_incidents
  FOR EACH ROW EXECUTE FUNCTION immutable_scanner_history();
